test('registration, rating, watchlist, recommendations, profile, logout, and login', async ({ page }) => {
  test.setTimeout(240_000)
  const username = 'phase6_browser_' + randomBytes(8).toString('hex')
  const password = 'Cinema-test-' + randomBytes(16).toString('hex')
  try {
    await page.goto('/register?next=/films/238')
    await page.getByLabel('Username', { exact: true }).fill(username)
    await page.getByLabel('Password', { exact: true }).fill(password)
    await page.getByRole('button', { name: 'Create account', exact: true }).click()
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('The Godfather')
    await expect(page.getByRole('button', { name: 'Add to watchlist', exact: true })).toBeEnabled()
    await page.getByRole('button', { name: 'Add to watchlist', exact: true }).click()
    await expect(page.getByRole('button', { name: 'In your watchlist', exact: true })).toBeEnabled()
    await page.getByRole('radio', { name: '4.5 out of 5 stars', exact: true }).check()
    await page.getByRole('button', { name: 'Save rating', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Your rating is saved.' })).toBeVisible()
    await page.goto('/collection')
    await expect(page.getByRole('link', { name: 'The Godfather, 1972', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Remove The Godfather from watchlist' }).click()
    await expect(page.getByRole('heading', { name: 'A blank screen. Endless possibilities.' })).toBeVisible()
    await page.goto('/collection?tab=ratings')
    await expect(page.getByText('Your rating: 4.5/5')).toBeVisible()
    await page.goto('/for-you')
    await expect(page.getByText('Inspired by your ratings')).toBeVisible()
    await expect(page.locator('.film-card').first()).toBeVisible()
    await expect(page.getByRole('link', { name: 'The Godfather, 1972', exact: true })).toHaveCount(0)
    await page.goto('/account')
    await page.getByLabel('Display name', { exact: true }).fill('Browser test profile')
    await page.getByRole('button', { name: 'Save profile', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Your profile is saved.' })).toBeVisible()
    await page.getByRole('button', { name: 'Sign out', exact: true }).click()
    await expect(page.getByRole('link', { name: 'Sign in', exact: true })).toBeVisible()
    await page.goto('/collection')
    await expect(page).toHaveURL(/\/login\?next=/)
    await page.getByLabel('Username', { exact: true }).fill(username)
    await page.getByLabel('Password', { exact: true }).fill(password)
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await expect(page.getByRole('heading', { level: 1 })).toContainText('A collection')
    await page.goto('/films/238')
    await page.getByRole('button', { name: 'Remove rating', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Rating removed.' })).toBeVisible()
    await page.goto('/account')
    await page.getByRole('button', { name: 'Sign out', exact: true }).click()
    await expect(page.getByRole('link', { name: 'Sign in', exact: true })).toBeVisible()
  } finally {
    const output = execFileSync(path.join(root, '.venv/Scripts/python.exe'), ['scripts/cleanup_phase6_test_account.py', username], { cwd: root, encoding: 'utf8', timeout: 60_000 })
    expect(output).toMatch(/Removed|No browser-test account/)
  }
})

test('empty results, missing film, network failure, and reduced motion have usable states', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/browse?q=phase6_no_matching_title_' + randomBytes(5).toString('hex'))
  await expect(page.getByRole('heading', { name: 'No films in this frame.' })).toBeVisible()
  await page.goto('/films/0')
  await expect(page.getByRole('heading', { name: 'This film is outside the frame.' })).toBeVisible()
  await page.route('**/api/v1/movies/?*', route => route.abort('failed'))
  await page.goto('/browse')
  await expect(page.getByRole('alert')).toContainText('Something interrupted the picture.')
  await page.unroute('**/api/v1/movies/?*')
  await page.getByRole('button', { name: 'Try again' }).click()
  await expect(page.locator('.film-card').first()).toBeVisible()
  const duration = await page.locator('.poster-link img').first().evaluate(element => getComputedStyle(element).transitionDuration)
  expect(duration).toBe('1e-05s')
})
