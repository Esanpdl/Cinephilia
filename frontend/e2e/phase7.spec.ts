import { test, expect } from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve('..')
const run = path.join(root, 'data/phase7/1bfb521f24cd2ecb715b')

test('people search renders the real API order and navigates to a film', async ({ page, request }) => {
  await page.goto('/browse')
  const search = page.getByRole('searchbox', { name: 'Search films' })
  await expect(search).toHaveAttribute('placeholder', /director, or actor/)
  await search.fill('chaplin')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page.getByText('Title matches first, then directors, then actors.')).toBeVisible()
  const response = await request.get('/api/v1/movies/?q=chaplin&ordering=rating')
  expect(response.ok()).toBe(true)
  const data = await response.json()
  expect(data.results.length).toBeGreaterThan(1)
  expect(data.results[0].title.toLowerCase()).toContain('chaplin')
  const links = page.locator('.film-card .poster-link')
  await expect(links).toHaveCount(data.results.length)
  expect(await links.evaluateAll(items => items.map(item => item.getAttribute('href'))))
    .toEqual(data.results.map((movie: { tmdb_id: number }) => '/films/' + movie.tmdb_id))
  await page.screenshot({ path: path.join(run, 'search-browser.png'), fullPage: true })
  await links.first().click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(data.results[0].title)
})

test('a newly imported source film is available through the existing site', async ({ page, request }) => {
  const verification = JSON.parse(fs.readFileSync(path.join(run, 'verification.json'), 'utf8'))
  expect(verification.passed).toBe(true)
  const movieId = verification.sample_new_tmdb_ids[0]
  const response = await request.get('/api/v1/movies/' + movieId + '/')
  expect(response.ok()).toBe(true)
  const movie = await response.json()
  expect(movie.is_technique_source).toBe(true)
  expect(movie.source_tags.some((source: string) => ['letterboxd_top1000', 'tspdt_top1000'].includes(source))).toBe(true)
  await page.goto('/films/' + movieId)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(movie.title)
  if (movie.directors.length) await expect(page.locator('.detail-director')).toContainText(movie.directors[0].name)
  if (movie.poster_url) await expect.poll(() => page.locator('.detail-poster img').evaluate((image: HTMLImageElement) => image.naturalWidth)).toBeGreaterThan(0)
  if (movie.trailer_embed_url) {
    await page.getByRole('button', { name: 'Play ' + movie.title + ' trailer', exact: true }).click()
    await expect(page.getByTitle(movie.title + ' trailer', { exact: true })).toHaveAttribute('src', movie.trailer_embed_url)
  } else {
    await expect(page.getByText("A trailer isn't available for this film.")).toBeVisible()
  }
  await page.screenshot({ path: path.join(run, 'new-source-film-browser.png'), fullPage: true })
})

test('release year range spans 1895 to the current year and combines with search', async ({ page, request }) => {
  await page.goto('/browse?q=clint&page=2')
  const from = page.getByRole('combobox', { name: 'From year' })
  const to = page.getByRole('combobox', { name: 'To year' })
  const currentYear = new Date().getUTCFullYear()
  await expect(from.locator('option[value="1895"]')).toHaveCount(1)
  await expect(to.locator(`option[value="${currentYear}"]`)).toHaveText(`Latest (${currentYear})`)
  await expect(to.locator(`option[value="${currentYear + 1}"]`)).toHaveCount(0)
  await from.selectOption('1970')
  await to.selectOption('1992')
  await expect(page).toHaveURL(/year_from=1970/)
  await expect(page).toHaveURL(/year_to=1992/)
  expect(new URL(page.url()).searchParams.has('page')).toBe(false)
  await expect(from.locator('option[value="2000"]')).toHaveJSProperty('disabled', true)
  const response = await request.get('/api/v1/movies/?q=clint&year_from=1970&year_to=1992&ordering=rating')
  expect(response.ok()).toBe(true)
  const data = await response.json()
  expect(data.count).toBeGreaterThan(0)
  expect(data.results.every((film: { release_date: string }) => Number(film.release_date.slice(0, 4)) >= 1970 && Number(film.release_date.slice(0, 4)) <= 1992)).toBe(true)
  const links = page.locator('.film-card .poster-link')
  await expect(links).toHaveCount(data.results.length)
  expect(await links.evaluateAll(items => items.map(item => item.getAttribute('href'))))
    .toEqual(data.results.map((film: { tmdb_id: number }) => '/films/' + film.tmdb_id))
  await page.reload()
  await expect(from).toHaveValue('1970')
  await expect(to).toHaveValue('1992')
  await expect(links).toHaveCount(data.results.length)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: path.join(run, 'year-range-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: 'Clear', exact: true }).click()
  await expect(from).toHaveValue('')
  await expect(to).toHaveValue('')
  await page.goto('/browse?year=1972')
  await expect(from).toHaveValue('1972')
  await expect(to).toHaveValue('1972')
})
